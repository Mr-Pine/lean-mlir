#!/usr/bin/env python3
"""Extract compiler-printed function regions and wrap them in Lean quotations.
Only alias/noalias metadata references are removed, since aliases are module-local.
Original whole-module MLIR is retained unchanged beside the extracted regions.
"""
import pathlib,re,json,hashlib,argparse
p=argparse.ArgumentParser();p.add_argument('directory',type=pathlib.Path);a=p.parse_args()
s=(a.directory/'generated/kernels.mlir').read_text()
portable=a.directory/'generated/portable.mlir'
if portable.exists(): s+='\n'+portable.read_text()
portable_xof=a.directory/'generated/portable_xof.mlir'
if portable_xof.exists(): s+='\n'+portable_xof.read_text()
lines=s.splitlines(); entries=[]
globals=[]
for i,line in enumerate(lines):
 if line.startswith('  "llvm.mlir.global"'):
  end=next(j for j in range(i+1,len(lines)) if lines[j]=='  }) : () -> ()')
  globals.extend(lines[i:end+1])
(a.directory/'generated/globals.mlir').write_text('\n'.join(globals)+'\n')
for i,line in enumerate(lines):
 m=re.search(r'sym_name = "(agave_[^"]+)"',line)
 if not m: continue
 name=m[1];end=next(j for j in range(i+1,len(lines)) if lines[j]=='  }) : () -> ()')
 raw='{\n'+'\n'.join(lines[i+1:end])+'\n}'
 region=re.sub(r'(?:alias_scopes|noalias_scopes) = \[[^\]]*\],? ?', '',raw)
 region=re.sub(r',\s*}>', '}>',region)
 (a.directory/'generated'/f'{name}.mlir').write_text(region+'\n')
 entry=region.splitlines()[1]
 args=re.findall(r'%[^: ,]+: (!llvm.ptr|i\d+|vector<[^>]+>)',entry)
 def lean_ty(x):
  if x=='!llvm.ptr':return 'SLLVM.Ty.ptr'
  if x.startswith('i'):return f'SLLVM.Ty.bitvec {x[1:]}'
  raise ValueError(x)
 # All emitted wrapper ABIs use pointers; void return (including sret).
 assert all(x=='!llvm.ptr' or x.startswith('i') for x in args),(name,args)
 lean=f'''-- Generated by lift.py from compiler-emitted MLIR; do not edit.
import SSA.Projects.SLLVM.Cfg
namespace AgaveLatticeHash.MLIR
open LeanMLIR SLLVM

{'set_option maxRecDepth 16384 in' if name == 'agave_batch_16' else ('set_option maxRecDepth 8192 in' if name in ('agave_portable_compress_pre', 'agave_portable_compress_xof', 'agave_portable_compress_in_place') or 'batch' in name else '')}
def {name}_region : MLIR.AST.Region 0 := [mlir_region|
{region}
]
'''
 # Full batch contains panic calls and needs linking; keep region but no CFG yet.
 if 'batch' not in name:
  lean+=f'\nsllvm_cfg_def {name} : Cfg (Ctxt.ofList [{", ".join(map(lean_ty,reversed(args)))}]) [] :=\n  [sllvm_cfg_of| {name}_region]\n'
 if 'batch' not in name and 'compress' not in name:
  lean+=f'\ndef {name}_com : Com SLLVM (Ctxt.ofList [{", ".join(map(lean_ty,reversed(args)))}]) .impure [] :=\n  [sllvm_of| {name}_region]\n'
 lean+='\nend AgaveLatticeHash.MLIR\n'
 (a.directory/f'{name}.lean').write_text(lean)
 entries.append({'symbol':name,'argument_types':args,'region_sha256':hashlib.sha256(region.encode()).hexdigest(),'operations':sorted(set(re.findall(r'"([\w.]+)"\(',region)))})
(a.directory/'generated/regions.json').write_text(json.dumps(entries,indent=2)+'\n')
# Decode the actual emitted byte initializer, independently of the Lean schedule.
schedule_name='alloc_61fb4a9344bbdaf2573accd6331d7e32'
schedule_line=next((line for line in globals if f'sym_name = "{schedule_name}"' in line),None)
if schedule_line is not None:
 literal=re.search(r'value = "([^"]*)"',schedule_line).group(1)
 assert re.fullmatch(r'(?:\\[0-9A-Fa-f]{2}){896}',literal), 'unexpected schedule initializer encoding'
 data=bytes(int(literal[i+1:i+3],16) for i in range(0,len(literal),3))
 words=[int.from_bytes(data[i:i+8],'little') for i in range(0,len(data),8)]
 literal_words=',\n  '.join(', '.join(f'{w}#64' for w in words[i:i+16]) for i in range(0,112,16))
 generated=f'''-- Generated solely from the compiler-emitted 896-byte global initializer.
import SSA.Projects.SLLVM.Cfg
namespace AgaveLatticeHash.MLIR

def scheduleGlobalName : String := "{schedule_name}"

def scheduleGlobalWords : Vector (BitVec 64) 112 := #v[
  {literal_words}]

def scheduleGlobalBits : BitVec 7168 := BitVec.packLanes scheduleGlobalWords

end AgaveLatticeHash.MLIR
'''
 (a.directory/'GeneratedGlobals.lean').write_text(generated)
 (a.directory/'generated/schedule.json').write_text(json.dumps({'symbol':schedule_name,'initializer_sha256':hashlib.sha256(data).hexdigest(),'words_le64':words},indent=2)+'\n')
