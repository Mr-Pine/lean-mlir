#!/usr/bin/env python3
"""Emit pure cache/normalization slices. Lean checks each against the pinned constructor."""
import argparse
import re
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parent
source = (root / 'Avx2Constructor.lean').read_text()
blocks = {}
for line in source.splitlines():
    header = re.match(r'  \^bb(\d+)', line)
    if header:
        block = int(header[1]); blocks[block] = []
    elif line.startswith('    '):
        blocks[block].append(line.strip())

head = '''import SSA.Projects.Agave.Ed25519.Proof.Tables.Avx2Constructor
import SSA.Projects.Agave.Ed25519.Proof.Avx2PointAdd.CFGSlice

/-! Exact pure instruction intervals of both inline cache conversions.
Generated by import_avx2_constructor_phases.py. Each equation is checked
against the unchanged imported block; the generator is not trusted.
The equations retain LLVM overflow flags, poison lanes, and bitcasts.
They do not assert that the final vectors are nonpoison or refine field values.
-/
namespace Agave.Ed25519.Tables.Avx2Constructor.CachePhases
open LeanMLIR.RIR
open Avx2PointAdd.CFG (runSlice runBodyFrom_slice)
set_option maxRecDepth 10000
set_option maxHeartbeats 4000000
set_option backward.isDefEq.respectTransparency false
attribute [local implicit_reducible] Ty.width

'''


def generate(name, bn, startreg, endreg):
    global head
    body = blocks[bn]
    start = next(i for i, line in enumerate(body) if line.startswith(f'%{startreg} ='))
    end = next(i for i, line in enumerate(body) if line.startswith(f'%{endreg} =')) + 1
    for phase, off in enumerate(range(start, end, 15)):
        n = min(15, end-off)
        nm = f'{name}{phase}'
        head += f'def {nm} (E : ⟪kernel.Γ⟫) : ⟪kernel.Γ⟫ :=\n'
        known = {}; dsts = []
        for line in body[off:off+n]:
            mat = re.fullmatch(r'%(\d+) = "llvm\.(\w+)"\(([^)]*)\)(.*?) : \(.*\) -> (.*)', line)
            assert mat, line
            dst, op, operands, attrs, ty = mat.groups(); dsts.append(dst)
            operands = [known.get(x, f'(E.read (%{x}))') for x in re.findall(r'%(\d+)', operands)]
            if ty.startswith('vector'):
                width, bits = map(int, re.fullmatch(r'vector<(\d+)xi(\d+)>', ty).groups())
                typ = f'⟦Ty.vec {width} {bits}⟧'
            else:
                typ = f'PoisonOr (BitVec {ty[1:]})'
            if op == 'shufflevector':
                mask = map(int, re.search(r'mask = array<i32: ([^>]+)>', attrs)[1].split(','))
                expr = 'Operation.shufflevector #v[' + ', '.join('none' if k < 0 else f'some {k}' for k in mask) + '] ' + ' '.join(operands)
            elif op == 'bitcast':
                expr = 'Operation.bitcast (by decide) ' + operands[0]
            elif op == 'insertelement':
                expr = 'Operation.insertelement ' + ' '.join(operands)
            elif op in ('sub', 'add', 'mul'):
                flags = int(re.search(r'overflowFlags = (\d+)', attrs)[1])
                fields = []
                if flags & 1: fields.append('nsw := true')
                if flags & 2: fields.append('nuw := true')
                expr = f'Vector.zipWith (Operation.{op} {{' + ', '.join(fields) + '}) ' + ' '.join(operands)
            elif op in ('and', 'lshr'):
                expr = f'Vector.zipWith (Operation.{op}' + (' false' if op == 'lshr' else '') + ') ' + ' '.join(operands)
            else:
                raise ValueError(line)
            head += f'  let v{dst} : {typ} := {expr}\n'
            known[dst] = f'v{dst}'
        head += '  E[' + ',\n    '.join(f'%{d} := v{d}' for d in dsts) + ']\n\n'
        head += f'''theorem {nm}_slice (p : Primitives) (E : ⟪kernel.Γ⟫) (s : GlobalState) :
    runSlice (kernel.bb{bn} p) E {off} {n} s = .value ({nm} E, s) := by
  simp [runSlice, kernel.bb{bn}, {nm}, List.foldlM_cons, List.foldlM_nil,
    Instr.run, UnOp.compute, BinOp.compute, TernOp.compute,
    EffectM.bind_eq, EffectM.pure_eq, mlir_env, -reduceShufflevector]

'''


generate('normalize', 0, 480, 504)
generate('initialCache', 0, 505, 649)
generate('successorCache', 2, 881, 1025)
head += 'end Agave.Ed25519.Tables.Avx2Constructor.CachePhases\n'
target = root / 'Avx2ConstructorCachePhases.lean'
if args.check:
    if target.read_text() != head:
        parser.error(f'generated source differs: {target}')
else:
    target.write_text(head)
print(('checked' if args.check else 'wrote'), len(head.splitlines()), 'lines')
