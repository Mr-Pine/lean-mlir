#!/usr/bin/env python3
"""Copy the pinned table-constructor bodies into exact RIR execution imports.

No instruction, attribute, SSA identifier, call or branch is changed. External
calls remain explicit effectful parameters. The source and region hashes bind
each generated module to the supplemental LLVM extraction manifest.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re


HERE = Path(__file__).resolve().parent
GENERATED = HERE.parent.parent / "MLIR/generated"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def generate(mode, extraction):
    source = GENERATED / f"agave_{mode}_table5.mlir"
    if sha(source.read_bytes()) != extraction["files_sha256"][source.name]:
        raise ValueError(f"constructor source changed: {source}")
    text = source.read_text()
    if text.count("  ^bb0(") != 1:
        raise ValueError(f"expected exactly one defined constructor: {source}")
    start = text.index("  ^bb0(")
    end = text.index("\n  }) : () -> ()", start)
    body = text[start:end]
    calls = {}
    for line in body.splitlines():
        match = re.search(r"callee = @([^, >}]+)", line)
        if not match:
            continue
        signature = line.rsplit(" : ", 1)[1]
        if not signature.endswith(" -> ()"):
            raise ValueError(f"unexpected call signature: {signature}")
        types = signature.removesuffix(" -> ()")[1:-1].split(", ")
        lean_types = [".ptr" if t == "!llvm.ptr" else f".bv {int(t[1:])}" for t in types]
        if match[1] in calls and calls[match[1]] != lean_types:
            raise ValueError(f"inconsistent call signature: {match[1]}")
        calls[match[1]] = lean_types
    globals_ = list(dict.fromkeys(re.findall(r"global_name = @([^, >}]+)", body)))
    ns = mode.title() + "Constructor"
    lines = [
        "module", "",
        "public import SSA.Projects.Agave.Ed25519.Proof.Verifier.ExecutionElab", "",
        "/-! Exact pinned width-five table constructor, generated by import_constructors.py.",
        "The original region and all operation attributes are retained. Primitive",
        "parameters expose the remaining field/point contracts; this import alone",
        "does not establish their behavior or the constructor's memory contents.",
        "-/", "", f"namespace Agave.Ed25519.Tables.{ns}", "",
        "open LeanMLIR.RIR LeanMLIR.RIR.ExecutionImport", "@[expose] public section", "",
        "structure Primitives where",
    ]
    for i, (name, types) in enumerate(calls.items()):
        lines += [f"  /-- `{name}` -/", f"  call{i} : Vals [{', '.join(types)}] → EffectM (Vals [])"]
    if globals_:
        lines += ["", "structure Globals where"]
        for i, name in enumerate(globals_):
            lines += [f"  /-- Exact immutable initializer for `{name}`. -/", f"  address{i} : Pointer"]
    parameters = "(p : Primitives)" + (" (g : Globals)" if globals_ else "")
    arguments = "p" + (" g" if globals_ else "")
    lines += ["", f"execution_def kernel {parameters} :=", "{", body, "}"]
    for i, name in enumerate(calls):
        lines.append(("with " if i == 0 else "  ") + f"@{name} := p.call{i}" +
                     ("," if i + 1 < len(calls) else ""))
    for i, name in enumerate(globals_):
        lines.append(("globals " if i == 0 else "  ") + f"@{name} := g.address{i}" +
                     ("," if i + 1 < len(globals_) else ""))
    blocks = sum(line.startswith("  ^bb") for line in body.splitlines())
    lines += ["", f"theorem block_count {parameters} : (kernel {arguments}).n = {blocks} := rfl",
              "", "end", f"end Agave.Ed25519.Tables.{ns}", ""]
    entry = {
        "symbol": extraction["kernels"][f"agave_{mode}_table5"]["target_symbol"],
        "source": str(source.relative_to(HERE.parent.parent)),
        "source_sha256": sha(source.read_bytes()),
        "region_sha256": sha(body.encode()),
        "region_lines": len(body.splitlines()),
        "blocks": blocks,
        "callees": calls,
        "globals": globals_,
        "normalizations": [],
    }
    return HERE / f"{ns}.lean", "\n".join(lines), entry


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    extraction_path = GENERATED / "table-manifest.json"
    extraction = json.loads(extraction_path.read_text())
    manifest = {
        "extraction_manifest_sha256": sha(extraction_path.read_bytes()),
        "generator_sha256": sha(Path(__file__).read_bytes()),
        "constructors": {},
    }
    for mode in ("serial", "avx2"):
        path, content, entry = generate(mode, extraction)
        if args.check:
            if path.read_text() != content:
                raise ValueError(f"stale constructor import: {path}")
        else:
            path.write_text(content)
        manifest["constructors"][mode] = entry
    target = HERE / "constructor-manifest.json"
    content = json.dumps(manifest, indent=2) + "\n"
    if args.check:
        if target.read_text() != content:
            raise ValueError(f"stale constructor manifest: {target}")
    else:
        target.write_text(content)


if __name__ == "__main__":
    main()
