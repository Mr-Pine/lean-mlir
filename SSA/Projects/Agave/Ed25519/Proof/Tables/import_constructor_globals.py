#!/usr/bin/env python3
"""Reproduce the exact relocation-free scalar table-constructor constant.

The source LLVM file is already pinned by MLIR/generated/table-manifest.json.
This supplemental import records its own input, byte, output and script hashes.
It does not normalize instructions or modify either constructor body.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SOURCE = ROOT / 'MLIR/generated/agave_serial_table5.ll'
SYMBOL = 'alloc_6e6f5bdc2dd4f9d83a28bc96071152e7'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def decode_llvm_bytes(value):
    data = bytearray()
    i = 0
    while i < len(value):
        if value[i] == '\\':
            data.append(int(value[i + 1:i + 3], 16))
            i += 3
        else:
            data.append(ord(value[i]))
            i += 1
    return bytes(data)


def generate():
    extraction = json.loads((ROOT / 'MLIR/generated/table-manifest.json').read_text())
    if sha(SOURCE.read_bytes()) != extraction['files_sha256'][SOURCE.name]:
        raise ValueError('pinned constructor LLVM changed')
    pattern = r'^@' + SYMBOL + r' = internal unnamed_addr constant \[40 x i8\] c"(.*?)", align 8$'
    matches = re.findall(pattern, SOURCE.read_text(), re.M)
    if len(matches) != 1:
        raise ValueError('expected one exact 40-byte constructor constant')
    data = decode_llvm_bytes(matches[0])
    if len(data) != 40:
        raise ValueError('wrong constructor constant length')
    literal = '0x' + data[::-1].hex()
    content = f'''import SSA.Projects.RIR.Global

/-! Exact constructor constant generated by import_constructor_globals.py.
LLVM source and byte hashes are recorded in constructor-globals-manifest.json. -/
namespace Agave.Ed25519.Tables
open LeanMLIR.RIR

-- Initializer SHA-256: {sha(data)}
def serialD2Bytes : BitVec 320 := {literal}

def serialD2Global : ByteGlobal :=
  ⟨"{SYMBOL}", 40, serialD2Bytes, 8, by decide⟩

end Agave.Ed25519.Tables
'''
    target = HERE / 'ConstructorGlobals.lean'
    manifest = {
        'source': str(SOURCE.relative_to(ROOT)),
        'source_sha256': sha(SOURCE.read_bytes()),
        'source_extraction_manifest_sha256': sha((ROOT / 'MLIR/generated/table-manifest.json').read_bytes()),
        'symbol': SYMBOL,
        'bytes': len(data),
        'alignment': 8,
        'initializer_sha256': sha(data),
        'little_endian_u64_words': [int.from_bytes(data[i:i + 8], 'little') for i in range(0, 40, 8)],
        'generator_sha256': sha(Path(__file__).read_bytes()),
        'output': target.name,
        'output_sha256': sha(content.encode()),
        'command': 'python3 Proof/Tables/import_constructor_globals.py',
        'normalizations': [],
    }
    return target, content, manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target, content, manifest = generate()
    manifest_path = HERE / 'constructor-globals-manifest.json'
    encoded = json.dumps(manifest, indent=2) + '\n'
    if args.check:
        if target.read_text() != content or manifest_path.read_text() != encoded:
            raise ValueError('stale constructor-global import or manifest')
    else:
        target.write_text(content)
        manifest_path.write_text(encoded)


if __name__ == '__main__':
    main()
