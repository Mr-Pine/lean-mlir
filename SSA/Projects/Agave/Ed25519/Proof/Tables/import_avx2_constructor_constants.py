#!/usr/bin/env python3
"""Emit exact constant-setup slices; Lean checks the generated equations."""
import argparse
import re
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = Path(__file__).resolve().parent
lines = []
for line in (root / 'Avx2Constructor.lean').read_text().splitlines():
    m = re.match(r'    %(\d+) = ', line)
    if m and int(m[1]) == 352:
        break
    if m:
        assert int(m[1]) == len(lines)
        lines.append(line.strip())
assert len(lines) == 352
head = '''import SSA.Projects.Agave.Ed25519.Proof.Tables.Avx2ConstructorTightPrefix
import SSA.Projects.Agave.Ed25519.Proof.Tables.Avx2ConstructorStack

/-! Exact constant and poison setup. Generated by import_avx2_constructor_constants.py;
all equations are checked against the unchanged imported constructor. -/
namespace Agave.Ed25519.Tables.Avx2Constructor.Constants
open LeanMLIR.RIR
open Avx2PointAdd.CFG (runSlice)
open DoubleBase.ExecutionAvx2 (RegisterFrame)
set_option maxRecDepth 20000
set_option maxHeartbeats 4000000
set_option backward.isDefEq.respectTransparency false
attribute [local implicit_reducible] Ty.width

'''
names = []
for off in range(0, 352, 32):
    phase = off // 32
    name = f'phase{phase}'
    names.append(name)
    head += f'def {name} (E : ⟪kernel.Γ⟫) : ⟪kernel.Γ⟫ :=\n'
    known, dsts = {}, []
    for line in lines[off:off+32]:
        mat = re.fullmatch(r'%(\d+) = "llvm\.([\w.]+)"\(([^)]*)\)(.*?) : \(.*\) -> (.*)', line)
        assert mat, line
        dst, op, operands, attrs, ty = mat.groups()
        dsts.append(dst)
        operands = [known.get(x, f'(E.read (%{x}))') for x in re.findall(r'%(\d+)', operands)]
        if ty.startswith('vector'):
            width, bits = map(int, re.fullmatch(r'vector<(\d+)xi(\d+)>', ty).groups())
            typ = f'⟦Ty.vec {width} {bits}⟧'
            tyexpr = f'(.vec {width} {bits})'
        else:
            bits = int(ty[1:]); width = None
            typ = f'PoisonOr (BitVec {bits})'
            tyexpr = f'(.bv {bits})'
        if op in ('mlir.poison', 'mlir.undef'):
            expr = f'Ty.poisoned {tyexpr}'
        elif op == 'mlir.constant':
            if width:
                val = re.search(r'value = dense<([^>]+)>', attrs)[1]
                if val.startswith('['):
                    vals = val[1:-1].split(',')
                    expr = '#v[' + ', '.join(f'.value {int(v)}#{bits}' for v in vals) + ']'
                else:
                    expr = f'Vector.replicate {width} (.value {val}#{bits})'
            else:
                val = re.search(r'value = (-?\d+)', attrs)[1]
                expr = f'.value {val}#{bits}'
        elif op == 'insertelement':
            expr = 'Operation.insertelement ' + ' '.join(operands)
        else:
            raise ValueError(line)
        head += f'  let v{dst} : {typ} := {expr}\n'
        known[dst] = f'v{dst}'
    head += '  E[' + ',\n    '.join(f'%{d} := v{d}' for d in dsts) + ']\n\n'
    head += f'''theorem {name}_slice (p : Primitives) (E : ⟪kernel.Γ⟫) (s : GlobalState) :
    runSlice (kernel.bb0 p) E {off} 32 s = .value ({name} E, s) := by
  simp [runSlice, kernel.bb0, {name}, List.foldlM_cons, List.foldlM_nil,
    Instr.run, Ty.wrap, TernOp.compute, EffectM.bind_eq, EffectM.pure_eq, mlir_env]

theorem {name}_frame (E : ⟪kernel.Γ⟫) :
    RegisterFrame {off} {off+32} E ({name} E) := by
  unfold {name}
  extract_lets
  iterate 32 apply RegisterFrame.write (hd := by decide)
  exact RegisterFrame.refl _ _ _

'''
head += 'def result (E : ⟪kernel.Γ⟫) : ⟪kernel.Γ⟫ :=\n  ' + ' ('.join(reversed(names)) + ' E' + ')'*(len(names)-1) + '\n\n'
head += '''theorem run (p : Primitives) (E : ⟪kernel.Γ⟫) (s : GlobalState) :
    runSlice (kernel.bb0 p) E 0 352 s = .value (result E, s) := by
'''
for i in range(11):
    head += f'  let E{i} := phase{i} ' + ('E' if i == 0 else f'E{i-1}') + '\n'
head += '  have h0 := phase0_slice p E s\n'
for i in range(1,11):
    head += f'  have h{i} := TightPrefix.runSlice_add (kernel.bb0 p) E E{i-1} E{i} 0 {32*i} 32 s s s h{i-1} (phase{i}_slice p E{i-1} s)\n'
head += '  exact h10\n\nend Agave.Ed25519.Tables.Avx2Constructor.Constants\n'
path = root/'Avx2ConstructorConstants.lean'
if args.check:
    if path.read_text() != head:
        parser.error(f'generated source differs: {path}')
else:
    path.write_text(head)
print(('checked' if args.check else 'wrote'), len(head.splitlines()), 'lines')
