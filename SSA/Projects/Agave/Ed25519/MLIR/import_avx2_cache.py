#!/usr/bin/env python3
"""Import the pinned cache CFG with explicit unsupported-instruction boundaries.

This is an instruction-abstraction import, not a claim that RIR implements x86
assembly or concurrent atomic events. Only CPUID, XGETBV, and the atomic store
are replaced with raw EffectM bindings. Every replacement is recorded verbatim
in the manifest; all ordinary operations and control flow remain unchanged.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

HERE = Path(__file__).resolve().parent
TARGET = HERE.parent / "Proof/Avx2Cache"
XGETBV = "_RNvNtNtNtCsgxBkk5gSRhY_4core9core_arch3x865xsave7__xgetbv"
CACHE = "_RNvNtNvNtCsjK63O35OHGN_14solana_ed255197backend20get_selected_backend10cpuid_avx27STORAGE"


def sha(text):
    return hashlib.sha256(text.encode()).hexdigest()


def generate():
    outputs, manifest = {}, {}
    extraction_path = HERE / "generated/avx2-cache-manifest.json"
    extraction = json.loads(extraction_path.read_text())
    for stem, name in [("agave_xgetbv", "xgetbv"), ("agave_initialize_avx2_cache", "initializer")]:
        path = HERE / "generated" / f"{stem}.mlir"
        source = path.read_text()
        assert sha(source) == extraction["kernels"][stem]["files_sha256"][path.name]
        start = source.index('    %0 = "llvm.mlir.constant"')
        body = source[start:source.index("\n  }) : () -> ()", start)]
        changed, replacements = [], []
        for line in body.splitlines():
            replacement = line
            if '"llvm.inline_asm"' in line:
                assert 'asm_string = "mov ${0:q}, rbx\\0Acpuid\\0Axchg ${0:q}, rbx"' in line
                assert 'constraints = "=&r,=&{ax},=&{cx},=&{dx},1,2,~{memory}"' in line
                assert 'asm_dialect = 1 : i64' in line and 'has_side_effects' in line
                replacement = re.sub(r'"llvm.inline_asm"(\([^)]*\)) <\{.*\}>',
                    r'"llvm.call"\1 <{callee = @cache_instruction_cpuid}>', line)
            elif '"llvm.call_intrinsic"' in line:
                assert 'intrin = "llvm.x86.xgetbv"' in line
                replacement = re.sub(r'"llvm.call_intrinsic"(\([^)]*\)) <\{.*\}>',
                    r'"llvm.call"\1 <{callee = @cache_instruction_xgetbv}>', line)
            elif '"llvm.store"' in line:
                assert line.strip() == '"llvm.store"(%23, %8) <{alignment = 1 : i64, ordering = 2 : i64}> : (i8, !llvm.ptr) -> ()'
                replacement = '    "llvm.call"(%23, %8) <{callee = @cache_instruction_store_monotonic}> : (i8, !llvm.ptr) -> ()'
            if replacement != line:
                replacements.append({"source": line.strip(), "boundary": replacement.strip()})
            changed.append(replacement)
        assert len(replacements) == (1 if name == "xgetbv" else 4)
        imported = "  ^bb0:\n" + "\n".join(changed)
        lines = ["module", "", "public import SSA.Projects.Agave.Ed25519.Proof.Verifier.ExecutionElab", "",
            "/-! Generated by MLIR/import_avx2_cache.py. The original CFG is preserved.",
            "Only unsupported CPUID/XGETBV/atomic-store instructions become explicit",
            "effect bindings. See avx2-cache-instruction-manifest.json. This is NOT an",
            "unconditional semantics theorem for those instructions. -/", "",
            "namespace Agave.Ed25519.Verifier.Execution.Dalek.Avx2Cache.Instructions", "",
            "open LeanMLIR.RIR", "@[expose] public section", ""]
        if name == "xgetbv":
            lines += ["execution_def xgetbv (instruction : Vals [.bv 32] → EffectM (Vals [.bv 64])) :=", "{", imported, "}",
                "with @cache_instruction_xgetbv := instruction"]
        else:
            lines += ["structure Primitives where",
                "  cpuid : Vals [.bv 32, .bv 32] → EffectM (Vals [.struct [.bv 32, .bv 32, .bv 32, .bv 32]])",
                "  xgetbv : Vals [] → EffectM (Vals [.bv 64])",
                "  storeMonotonic : Vals [.bv 8, .ptr] → EffectM (Vals [])", "",
                "execution_def initializer (p : Primitives) (cache : Pointer) :=", "{", imported, "}",
                "with @cache_instruction_cpuid := p.cpuid,",
                f"  @{XGETBV} := p.xgetbv,",
                "  @cache_instruction_store_monotonic := p.storeMonotonic",
                f"globals @{CACHE} := cache", "",
                "theorem initializer_block_count (p : Primitives) (cache : Pointer) :",
                "    (initializer p cache).n = 3 := rfl"]
        lines += ["", "end", "end Agave.Ed25519.Verifier.Execution.Dalek.Avx2Cache.Instructions", ""]
        dest = TARGET / ("XgetbvProgram.lean" if name == "xgetbv" else "InitializerProgram.lean")
        outputs[dest] = "\n".join(lines)
        manifest[name] = {"source": str(path.relative_to(HERE)), "source_sha256": sha(source),
            "region_sha256": sha(body), "imported_region_sha256": sha(imported),
            "instruction_boundaries": replacements, "other_instruction_changes": []}
    manifest["importer_sha256"] = sha(Path(__file__).read_text())
    manifest["extraction_manifest_sha256"] = sha(extraction_path.read_text())
    outputs[HERE / "generated/avx2-cache-instruction-manifest.json"] = json.dumps(manifest, indent=2) + "\n"
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, text in generate().items():
        if args.check:
            assert path.read_text() == text, f"stale {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print("Validated AVX2 cache instruction boundaries" if args.check else "Wrote AVX2 cache instruction boundaries")


if __name__ == "__main__":
    main()
