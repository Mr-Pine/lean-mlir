#!/usr/bin/env python3
"""Quote the exact SHA-512 compression regions, preserving all operations.

External CPUID initialization and the AVX2 call remain named effectful
boundaries. Globals remain explicit addresses; no cache contents or round
constant values are assumed by successful import alone.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

from extract_sha512_compress import check_artifacts

HERE = Path(__file__).resolve().parent
TARGET = HERE.parent / "Proof/SHA512/Compression"
REGIONS = {
    "Dispatch": "agave_sha512_compress_dispatch",
    "Avx2": "agave_sha512_compress_avx2",
}
CALLEES = {
    "4sha26sha5128x86_avx28compress": "avx2Compress",
    "4sha26sha51210avx2_cpuid8init_get10init_inner": "initializeAvx2Cache",
}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def ty(spelling):
    if spelling == "!llvm.ptr":
        return ".ptr"
    assert re.fullmatch(r"i\d+", spelling), spelling
    return f".bv {spelling[1:]}"


def tys(spelling):
    return [] if spelling == "()" else [ty(t) for t in spelling.strip("()").split(", ")]


def quoted(symbol):
    return symbol if re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", symbol) else json.dumps(symbol)


def extract_region(text, expected):
    # Bind the region to its enclosing function, not the first basic block
    # in an arbitrary module. Declarations cannot satisfy this match.
    functions = list(re.finditer(
        r'^  "llvm.func"\(\) <\{([^\n]+)\}> \(\{\n(  \^bb0\(.*?)(?=\n  \}\) : \(\) -> \(\))',
        text, re.M | re.S))
    assert len(functions) == 1, "expected one defined function"
    function, = functions
    header, body = function.groups()
    function_symbol, = re.findall(r'sym_name = "([^"\n]+)"', header)
    assert function_symbol == expected, (function_symbol, expected)
    signature, = re.findall(r'function_type = (!llvm.func<[^>]+>)', header)
    assert signature == "!llvm.func<void (ptr, ptr, i64)>", signature
    assert body.splitlines()[0] == "  ^bb0(%arg0: !llvm.ptr, %arg1: !llvm.ptr, %arg2: i64):"
    return function_symbol, signature, body


def generate():
    outputs, inventory = {}, {}
    extraction = check_artifacts(HERE / "generated")
    for name, stem in REGIONS.items():
        source = HERE / "generated" / f"{stem}.mlir"
        text = source.read_text()
        function_symbol, signature, body = extract_region(
            text, extraction["kernels"][stem]["target_symbol"])
        calls = {}
        for line in body.splitlines():
            symbol = re.search(r"callee = @([^, >}]+)", line)
            if not symbol:
                continue
            field, = [field for suffix, field in CALLEES.items() if symbol[1].endswith(suffix)]
            args, returns = line.rsplit(" : ", 1)[1].split(" -> ")
            entry = {"field": field, "args": tys(args), "returns": tys(returns)}
            assert symbol[1] not in calls or calls[symbol[1]] == entry
            calls[symbol[1]] = entry
        globals_ = list(dict.fromkeys(re.findall(r"global_name = @([^, >}]+)", body)))
        lines = [
            "module", "", "public import SSA.Projects.Agave.Ed25519.Proof.Verifier.ExecutionElab", "",
            "/-! Exact original sha2 0.11.0 region. Generated by import_sha512_compress.py.",
            "All instructions, including cache loads and volatile constant loads, remain present.",
            "RIR models loaded values and memory effects, not a volatile event trace.",
            "Successful import is distinct from an execution refinement. -/", "",
            f"namespace Agave.Ed25519.SHA512.Execution.{name}", "",
            "open LeanMLIR.RIR", "@[expose] public section", "",
            "set_option maxHeartbeats 4000000", "set_option maxRecDepth 100000", "",
        ]
        binders, arguments = [], []
        if calls:
            lines += ["structure Primitives where"]
            for symbol, entry in calls.items():
                lines += [f"  /-- Exact external symbol `{symbol}`. -/",
                          f"  {entry['field']} : Vals [{', '.join(entry['args'])}] → EffectM (Vals [{', '.join(entry['returns'])}])"]
            lines += [""]
            binders.append("(p : Primitives)")
            arguments.append("p")
        if globals_:
            lines += ["structure Globals where"]
            for i, symbol in enumerate(globals_):
                lines += [f"  /-- `{symbol}`: contents and mutability are separate memory obligations. -/",
                          f"  address{i} : Pointer"]
            lines += [""]
            binders.append("(g : Globals)")
            arguments.append("g")
        rendered = body
        quoted_symbols = []
        for symbol in [*calls, *globals_]:
            if quoted(symbol) != symbol:
                rendered = re.sub("@" + re.escape(symbol) + r"(?=[, >}])",
                                  lambda _: "@" + quoted(symbol), rendered)
                quoted_symbols.append(symbol)
        lines += [f"execution_def program {' '.join(binders)} :=", "{", rendered, "}"]
        if calls:
            lines += ["with " + ",\n  ".join(
                f"@{quoted(symbol)} := p.{entry['field']}" for symbol, entry in calls.items())]
        if globals_:
            lines += ["globals " + ",\n  ".join(
                f"@{quoted(symbol)} := g.address{i}" for i, symbol in enumerate(globals_))]
        count = len(re.findall(r"^  \^bb\d", body, re.M))
        lines += ["", f"theorem block_count {' '.join(binders)} : (program {' '.join(arguments)}).n = {count} := rfl",
                  "", "end", f"end Agave.Ed25519.SHA512.Execution.{name}", ""]
        outputs[TARGET / f"{name}Program.lean"] = "\n".join(lines)
        inventory[name] = {"source": str(source.relative_to(HERE)), "source_sha256": sha(source),
                           "function_symbol": function_symbol, "function_type": signature,
                           "region_sha256": hashlib.sha256(body.encode()).hexdigest(),
                           "callees": calls, "globals": globals_, "blocks": count,
                           "normalizations": [{"symbol_quoting": s} for s in quoted_symbols]}
    inventory["import_inputs_sha256"] = {
        str(p.relative_to(HERE.parent)): sha(p)
        for p in (Path(__file__), HERE / "extract_sha512_compress.py",
                  HERE / "generated/sha512-compress-manifest.json",
                  HERE.parent / "Proof/Verifier/ExecutionElab.lean")}
    outputs[HERE / "generated/sha512-compress-rir-manifest.json"] = json.dumps(inventory, indent=2) + "\n"
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, source in generate().items():
        if args.check:
            assert path.read_text() == source, f"stale {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(source)
    print("Validated exact compression imports" if args.check else "Wrote exact compression imports")


if __name__ == "__main__":
    main()
