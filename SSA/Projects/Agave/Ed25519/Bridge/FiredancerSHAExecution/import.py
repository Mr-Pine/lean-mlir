#!/usr/bin/env python3
"""Reproduce exact scalar Firedancer SHA C -> LLVM -> MLIR -> RIR artifacts.

No instruction rewrite, C wrapper, or post-Clang inlining is used. --check
checks stored artifact hashes and regenerates the RIR text without a C checkout.
"""
import argparse
from collections import Counter
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

HERE = Path(__file__).resolve().parent
PIN = "292f89b338a634e23e9f45c3dfdd5383ddcae624"
NAMES = {"Init": "fd_sha512_init", "Core": "fd_sha512_core_ref",
         "Append": "fd_sha512_append", "Finish": "fd_sha512_fini"}

def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()

def generate():
    lines = ["module", "", "public import SSA.Projects.Agave.Ed25519.Proof.Verifier.ExecutionElab", "",
      "/-! Generated by Bridge/FiredancerSHAExecution/import.py. Exact scalar C regions.",
      "Import success is not an execution or cryptographic correctness theorem. -/", "",
      "namespace Agave.Ed25519.Bridge.FiredancerSHAExecution", "open LeanMLIR.RIR",
      "@[expose] public section", ""]
    info = {}
    for namespace, symbol in NAMES.items():
        mlir = (HERE / "generated" / (symbol + ".mlir")).read_text()
        start = mlir.index("  ^bb0(")
        body = mlir[start:mlir.index("\n  }) : () -> ()", start)]
        calls = list(dict.fromkeys(re.findall(r"callee = @([^, >}]+)", body)))
        assert all(s == "fd_sha512_core_ref" for s in calls), calls
        globals_ = list(dict.fromkeys(re.findall(r"global_name = @([^, >}]+)", body)))
        assert all(s == "fd_sha512_core_ref.K" for s in globals_), globals_
        lines += ["namespace " + namespace, ""]
        binders = []
        args = []
        if calls:
            binders += ["(core : Vals [.ptr, .ptr, .bv 64] → EffectM (Vals []))"]
            args += ["core"]
        if globals_:
            binders += ["(constants : Pointer)"]
            args += ["constants"]
        rendered = body.replace("@fd_sha512_core_ref.K", '@"fd_sha512_core_ref.K"')
        lines += ["execution_def program " + " ".join(binders) + " :=", "{", rendered, "}"]
        if calls:
            lines += ["with @fd_sha512_core_ref := core"]
        if globals_:
            lines += ['globals @"fd_sha512_core_ref.K" := constants']
        n = len(re.findall(r"^  \^bb[0-9]+", body, re.M))
        lines += ["", "theorem block_count " + " ".join(binders) + " : (program " + " ".join(args) + ").n = " + str(n) + " := rfl", "", "end " + namespace, ""]
        info[namespace] = {"symbol": symbol, "blocks": n, "region_sha256": hashlib.sha256(body.encode()).hexdigest(),
            "external_calls": calls, "global_addresses": globals_,
            "operations": dict(sorted(Counter(re.findall(r'"(llvm\.[^"]+)"\(', body)).items()))}
    lines += ["end", "end Agave.Ed25519.Bridge.FiredancerSHAExecution", ""]
    return "\n".join(lines), info

def initializer_data():
    text = (HERE / "generated/fd_sha512_core_ref.ll").read_text()
    line, = [line for line in text.splitlines() if line.startswith("@fd_sha512_core_ref.K =")]
    values = [int(x) % 2**64 for x in re.findall(r"i64 (-?[0-9]+)", line)]
    assert len(values) == 80
    packed = sum(v << (64 * i) for i, v in enumerate(values))
    return "\n".join([
        "import SSA.Projects.RIR.Global", "",
        "/-! Generated from the pinned Firedancer LLVM constant initializer. -/",
        "namespace Agave.Ed25519.Bridge.FiredancerSHAExecution",
        "open LeanMLIR.RIR", "",
        "def constantsBytes : BitVec 5120 := " + hex(packed), "",
        "def constantsGlobal : ByteGlobal :=",
        '  ⟨"fd_sha512_core_ref.K", 640, constantsBytes, 16, by decide⟩', "",
        "end Agave.Ed25519.Bridge.FiredancerSHAExecution", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("/home/nine/Documents/firedancer"))
    parser.add_argument("--llvm-bin", type=Path, default=Path("/tmp/ed25519-rir-extract/tools/root/usr/lib/llvm-22/bin"))
    parser.add_argument("--llvm-lib", default="/tmp/ed25519-rir-extract/tools/root/usr/lib/x86_64-linux-gnu")
    parser.add_argument("--clang", default="/usr/bin/clang")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest_path = HERE / "manifest.json"
    if args.check:
        manifest = json.loads(manifest_path.read_text())
        for name, digest in manifest["artifacts_sha256"].items():
            assert sha(HERE / name) == digest, name
        text, info = generate()
        assert (HERE / "Program.lean").read_text() == text
        assert manifest["regions"] == info
        assert (HERE / "InitializerData.lean").read_text() == initializer_data()
        print("Four exact Firedancer SHA regions and artifact hashes checked")
        return
    source = args.source.resolve()
    assert subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=source, text=True).strip() == PIN
    out = HERE / "generated"
    out.mkdir(exist_ok=True)
    env = os.environ | {"LD_LIBRARY_PATH": args.llvm_lib}
    commands = []
    def run(cmd):
        cmd = list(map(str, cmd))
        subprocess.run(cmd, cwd=source, env=env, check=True)
        commands.append(cmd)
    flags = ["-S", "-emit-llvm", "-O1", "-fno-vectorize", "-fno-slp-vectorize", "-fno-unroll-loops",
             "-DFD_SHA512_CORE_IMPL=0", "-DFD_HAS_AVX=0", "-DFD_HAS_AVX512=0"]
    full = out / "fd_sha512.ll"
    depfile = out / "fd_sha512.d"
    run([args.clang, *flags, "-MMD", "-MF", depfile, "-o", full, "src/ballet/sha512/fd_sha512.c"])
    deps = depfile.read_text().replace("\\\n", " ").split(":", 1)[1].split()
    deps = sorted(set(str((source / p).resolve().relative_to(source)) for p in deps))
    assert not subprocess.check_output(["git", "status", "--porcelain", "--", *deps], cwd=source, text=True)
    depfile.unlink()
    for symbol in NAMES.values():
        ll, mlir = out / (symbol + ".ll"), out / (symbol + ".mlir")
        run([args.llvm_bin / "llvm-extract", "--keep-const-init", "--func=" + symbol, "-S", full, "-o", ll])
        run([args.llvm_bin / "opt", "-S", "--passes=internalize,globaldce", "--internalize-public-api-list=" + symbol, ll, "-o", ll])
        run([args.llvm_bin / "mlir-translate", "--import-llvm", "--mlir-print-op-generic", ll, "-o", mlir])
    text, info = generate()
    (HERE / "Program.lean").write_text(text)
    (HERE / "InitializerData.lean").write_text(initializer_data())
    manifest = {"source_commit": PIN, "source_repository": "firedancer", "source_files_sha256": {p: sha(source / p) for p in deps},
        "target": "x86_64-pc-linux-gnu, LP64, little-endian, scalar FD_SHA512_CORE_IMPL=0",
        "tools": {str(tool): subprocess.check_output([str(tool), "--version"], env=env, text=True) for tool in [args.clang, args.llvm_bin / "llvm-extract", args.llvm_bin / "opt", args.llvm_bin / "mlir-translate"]},
        "commands": commands, "regions": info,
        "boundary": "Pinned scalar C compilation and LLVM/MLIR translation are trusted. Only body regions are imported; function attributes and target ABI are recorded artifacts, not RIR theorems. K global initialization is a separate memory obligation. Append/Finish expose exactly one typed core call boundary. No equivalence to the older unpinned SLLVM Firedancer lift is asserted.",
        "artifacts_sha256": {str(p.relative_to(HERE)): sha(p) for p in [Path(__file__), HERE / "Program.lean", HERE / "InitializerData.lean", *sorted(out.glob("*.ll")), *sorted(out.glob("*.mlir"))]}}
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    print("Extracted and imported four pinned scalar Firedancer SHA bodies")

if __name__ == "__main__":
    main()
