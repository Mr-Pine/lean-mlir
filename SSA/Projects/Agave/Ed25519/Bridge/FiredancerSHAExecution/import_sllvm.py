#!/usr/bin/env python3
"""Import the pinned scalar SHA MLIR regions into the legacy SLLVM dialect.

Only the generic attribute spelling changes. Instructions, operands, types,
block edges and opaque metadata payloads are retained. The trusted compiler
boundary and original source pin are inherited from manifest.json. --check
checks every input hash and exactly regenerates all four stored Lean modules.
Import success alone does not prove execution or cross-dialect equivalence.
"""
from pathlib import Path
import argparse
import re, json, hashlib
p = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
options = parser.parse_args()
source_manifest = json.loads((p / 'manifest.json').read_text())
assert source_manifest['source_commit'] == '292f89b338a634e23e9f45c3dfdd5383ddcae624'
for name, digest in source_manifest['artifacts_sha256'].items():
    assert hashlib.sha256((p / name).read_bytes()).hexdigest() == digest, name
heads={
'Init': ('fd_sha512_init','[SLLVM.Ty.ptr]','[SLLVM.Ty.ptr]'),
'Core': ('fd_sha512_core_ref','[SLLVM.Ty.bitvec 64, SLLVM.Ty.ptr, SLLVM.Ty.ptr]','[]'),
'Append': ('fd_sha512_append','[SLLVM.Ty.bitvec 64, SLLVM.Ty.ptr, SLLVM.Ty.ptr]','[SLLVM.Ty.ptr]'),
'Finish': ('fd_sha512_fini','[SLLVM.Ty.ptr, SLLVM.Ty.ptr]','[SLLVM.Ty.ptr]')}
for n,(symbol,args,ret) in heads.items():
 text=(p/'generated'/f'{symbol}.mlir').read_text(); start=text.index('  ^bb0('); body=text[start:text.index('\n  }) : () -> ()',start)]
 flags={'0':'#llvm.overflow<none>','1':'#llvm.overflow<nsw>','2':'#llvm.overflow<nuw>','3':'[#llvm.overflow<nsw>, #llvm.overflow<nuw>]'}
 body=re.sub(r'overflowFlags = ([0-3]) : i32',lambda m:'overflowFlags = '+flags[m[1]],body)
 body=re.sub(r'#llvm.constant_range<([^>]*)>', lambda m:'#llvm.constant_range<'+json.dumps(m[1])+'>', body)
 body=re.sub(r'#llvm.memory_effects<([^>]*)>', lambda m:'#llvm.memory_effects<'+json.dumps(m[1])+'>', body)
 body=re.sub(r'#llvm.tailcallkind<([^>]*)>', lambda m:'#llvm.tailcallkind<'+json.dumps(m[1])+'>', body)
 body=body.replace('op_bundle_sizes = array<i32>', 'op_bundle_sizes = array<i32: >')
 body=re.sub(r'#(llvm\.[A-Za-z_]+)<([A-Za-z_]+)>', lambda m:'#'+m[1]+'<'+json.dumps(m[2])+'>', body)
 body=body.replace('@fd_sha512_core_ref.K','@"fd_sha512_core_ref.K"')
 imp='SSA.Projects.Agave.Ed25519.Bridge.FiredancerSHAExecution.SLLVMSourceCore' if n in ('Append','Finish') else 'SSA.Projects.SLLVM.Cfg'
 suffix=' with @fd_sha512_core_ref := core' if n in ('Append','Finish') else ''
 out=f'''module

public import {imp}
public meta import {imp}

/-! Generated by import_sllvm.py from the same pinned SHA region as Program.lean.
Numeric overflow flags use their legacy spelling; modern opaque attributes
and empty arrays use syntax accepted by the legacy generic parser.
Instruction order, operands, types, block edges and attribute values are retained.
This inherits SLLVM's documented semantics, including ignored GEP inbounds
flags. Import alone is not a proof of source/RIR correspondence. -/

namespace Agave.Ed25519.Bridge.FiredancerSHAExecution.SLLVMSource
open LeanMLIR SLLVM
@[expose] public section
set_option maxRecDepth 3000
set_option maxHeartbeats 4000000

def {n.lower()}Region : MLIR.AST.Region 0 := [mlir_region|
{{
{body}
}}
]

sllvm_cfg_def {n.lower()} : Cfg (Ctxt.ofList {args}) {ret} :=
  [sllvm_cfg_of| {n.lower()}Region{suffix}]

end
end Agave.Ed25519.Bridge.FiredancerSHAExecution.SLLVMSource
'''
 target = p / f'SLLVMSource{n}.lean'
 if options.check:
  assert target.read_text() == out, target
 else:
  target.write_text(out)
print('Four pinned SHA SLLVM source regions ' + ('checked' if options.check else 'generated'))
